// Regenerates src/contract/stakeSweat.ts (ABI + creation bytecode) from the Foundry artifact.
// Usage: forge build && bun run scripts/gen-contract.ts
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'

const artifactPath = 'contracts/out/StakeAndSweat.sol/StakeAndSweat.json'
const artifact = JSON.parse(readFileSync(artifactPath, 'utf8')) as {
  abi: unknown[]
  bytecode: { object: string }
}

mkdirSync('src/contract', { recursive: true })
const out = `// Generated by scripts/gen-contract.ts from ${artifactPath}. Do not edit by hand.
export const STAKE_SWEAT_ABI = ${JSON.stringify(artifact.abi, null, 2)} as const

export const STAKE_SWEAT_BYTECODE = '${artifact.bytecode.object}' as const
`
writeFileSync('src/contract/stakeSweat.ts', out)
console.log(`wrote src/contract/stakeSweat.ts (${artifact.abi.length} abi items)`)
